import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync, createWriteStream, cpSync } from 'node:fs';
import { resolve, join } from 'node:path';
const plan = JSON.parse(readFileSync('data/phase2-plan.json','utf8'));
const name = process.argv[2];
if (!plan.modules.some(m=>m.slug===name)) throw new Error('Choose: '+plan.modules.map(m=>m.slug).join(', '));
const parent = resolve(process.env.PHASE2_ARCHIVE_ROOT || 'blob-report/archive/phase2-2026-10-25'); mkdirSync(parent,{recursive:true}); mkdirSync('test-results',{recursive:true});
let attempt=1; while(existsSync(join(parent,`${name}-${attempt}`))) attempt++;
const stage=join(parent,`${name}-${attempt}`); mkdirSync(stage);
const args=['node_modules/playwright/cli.js','test','--config=playwright.phase2.config.ts',...process.argv.slice(3)];
const meta={module:name,attempt,started:new Date().toISOString(),stage,args,scope:'Phase 2 QA company only; no external payments/email, no existing-staff credential changes'};
writeFileSync(join(stage,'execution.json'),JSON.stringify(meta,null,2));
console.log('PHASE2_EVIDENCE='+stage);
const log=createWriteStream(join(stage,'console.log'));
const child=spawn(process.execPath,args,{env:{...process.env,PHASE2_MODULE:name,PHASE2_STAGE:stage},stdio:['ignore','pipe','pipe']});
for(const stream of [child.stdout,child.stderr]) stream.on('data',d=>{process.stdout.write(d);log.write(d);});
const code=await new Promise((done,reject)=>{child.on('close',done);child.on('error',reject);});
await new Promise(done=>log.end(done));
meta.finished=new Date().toISOString();meta.exitCode=code;
writeFileSync(join(stage,'execution.json'),JSON.stringify(meta,null,2));
if(existsSync('test-results/phase2-journal.json')) cpSync('test-results/phase2-journal.json',join(stage,'safe-journal.json'));
if(existsSync(join(stage,'results.json'))) console.log('PHASE2_STATS='+JSON.stringify(JSON.parse(readFileSync(join(stage,'results.json'),'utf8')).stats));
process.exitCode=Number(code??1);
